					<article class="post-article">
						<div class="post-rich w-richtext">
							<p>Harbor Family runs three locations and about forty visits a day per site. Before
								Carefront, roughly one in six appointments ended as a no-show. Not because patients did
								not care, but because a reminder they could not answer was easy to ignore.</p>
							<h2 id="one-way">The problem with one-way reminders</h2>
							<p>A reminder that says "reply STOP to opt out" teaches people that the message is not for
								them. The front desk then spent the morning calling the people who did not show up,
								instead of the people who would have rescheduled if anyone had asked.</p>
							<blockquote>We stopped chasing patients. The schedule started fixing itself, because people
								could just text back. Dr. Lena Ortiz, Medical director</blockquote>
							<h2 id="replies">Letting patients reply</h2>
							<p>Every reminder now arrives as a normal text from the clinic number. Patients reply with a
								time, a question or a simple yes, and the reply lands in the same thread the front desk
								already works from.</p>
							<ul>
								<li>Reminders 72 hours and 2 hours before the visit</li>
								<li>Replies routed to whoever owns that patient today</li>
								<li>Reschedule links that respect provider buffers</li>
							</ul>
							<h2 id="waitlist">A waitlist that fills itself</h2>
							<p>When a patient cancels, Carefront offers the slot to the waitlist in order, by text, with
								a two-hour hold. Most freed slots are filled before anyone on the team notices they
								opened.</p>
							<h3>The confirmation text</h3>
							<p>The smallest change had the biggest effect. The confirmation now names the provider and
								the room, and asks one question: "Still good for Friday at 10:15?" A yes takes one tap.
								A no opens the reschedule link.</p>
							<h2 id="results">What changed in 90 days</h2>
							<p>Within ninety days no-shows were down by a third across all three locations, and the
								morning call list was gone. The front desk now spends that hour on new patient calls.
							</p>
